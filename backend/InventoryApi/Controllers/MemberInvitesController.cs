using Inventory.Application.Access;
using Inventory.Application.Members;
using InventoryApi.Auth;
using InventoryApi.DTOs;
using Microsoft.AspNetCore.Authorization;
using Microsoft.AspNetCore.Mvc;
using Microsoft.Identity.Web.Resource;

namespace InventoryApi.Controllers;

/// <summary>
/// The invite links of the signed-in Owner's business (issue #531): create one, see them all, and
/// cancel one that has not been used.
///
/// <para>Owner-only, exactly as <see cref="MembersController"/> is, and for the same reason: the
/// controller declares <c>Members.Manage</c>, which #328's agreed table gives to an Owner alone, so
/// a Manager and an Operator are refused by the authorization middleware before any action runs -
/// with a bare <c>403</c> that describes neither the capability nor the caller's role. Reading the
/// list is as restricted as creating one: an invite list is the record of who was offered access to
/// the business.</para>
///
/// <para>No action takes a business identifier of any kind, and none takes an owner, an expiry or a
/// token. The business is resolved from the authenticated actor's membership; the expiry is the
/// fixed seven-day lifetime of <c>MemberInvitePolicy</c>; and the token is generated by the server,
/// returned once in the creation response and stored only as a hash. The invite key the cancel
/// action takes is looked up only within the caller's own business, so another business's key is
/// simply not found rather than refused in a way that confirms it exists.</para>
///
/// <para>Refusals are mapped centrally. An unsupported role name or an over-long note throws
/// <c>DomainValidationException</c>, which <see cref="Http.DomainExceptionHandler"/> answers as
/// <c>400</c>; an invite that cannot be cancelled because it was already used, has expired, or
/// holds a state this deployment does not declare throws <c>DomainConflictException</c> and is
/// answered as <c>409 Conflict</c> with the Domain's own sentence. Neither message names another
/// business, member or invite, and no message carries a token.</para>
///
/// <para>Redeeming an invite is deliberately not here: it is issue #532's separate endpoint, which
/// is reached by a signed-in person who has no membership yet and so has its own authorization
/// shape entirely.</para>
/// </summary>
[ApiController]
[Route("api/members/invites")]
[Authorize]
[RequiredScope("access_as_user")]
[RequireCapability(Capability.MembersManage)]
public sealed class MemberInvitesController : ControllerBase
{
    private readonly CreateMemberInvite _createInvite;
    private readonly ListMemberInvites _listInvites;
    private readonly CancelMemberInvite _cancelInvite;

    public MemberInvitesController(
        CreateMemberInvite createInvite,
        ListMemberInvites listInvites,
        CancelMemberInvite cancelInvite)
    {
        _createInvite = createInvite;
        _listInvites = listInvites;
        _cancelInvite = cancelInvite;
    }

    /// <summary>
    /// Creates one single-use invite link. The token comes back in this response and never again.
    /// </summary>
    [HttpPost]
    public async Task<ActionResult<CreatedMemberInviteResponse>> Create(
        CreateMemberInviteRequest request,
        CancellationToken cancellationToken)
    {
        ArgumentNullException.ThrowIfNull(request);

        var created = await _createInvite.Handle(request.Role, request.Note, cancellationToken);

        // The created invite's own collection is where it is visible from here on; there is no
        // single-invite read, because the only thing a client could not already see on the list is
        // the token, which this response is the one and only carrier of.
        return CreatedAtAction(
            nameof(List),
            null,
            new CreatedMemberInviteResponse(created.Token, ToResponse(created.Invite)));
    }

    /// <summary>Every invite of the caller's business, in every state.</summary>
    [HttpGet]
    public async Task<ActionResult<IReadOnlyList<MemberInviteResponse>>> List(CancellationToken cancellationToken)
    {
        var invites = await _listInvites.Handle(cancellationToken);

        return Ok(invites.Select(ToResponse).ToList());
    }

    /// <summary>
    /// Withdraws one invite that has not been used. A replay is accepted and changes nothing.
    /// </summary>
    [HttpPost("{inviteId:int}/cancel")]
    public async Task<ActionResult<MemberInviteResponse>> Cancel(
        int inviteId,
        CancellationToken cancellationToken)
    {
        var invite = await _cancelInvite.Handle(inviteId, cancellationToken);

        return invite is null ? NotFound() : Ok(ToResponse(invite));
    }

    private static MemberInviteResponse ToResponse(MemberInvite invite) =>
        new(
            invite.InviteId,
            invite.Role?.ToString(),
            invite.Note,
            invite.Status?.ToString(),
            invite.CreatedAtUtc,
            invite.ExpiresAtUtc,
            invite.UsedAtUtc,
            invite.CancelledAtUtc,
            invite.RedeemedByMembershipId);
}
